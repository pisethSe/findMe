export const PHNOM_PENH_DEMO_BOUNDS = {
  north: 11.75,
  south: 11.4,
  east: 105.05,
  west: 104.7,
} as const;

export function isInsidePhnomPenhDemoBounds(location: {
  latitude: number;
  longitude: number;
}): boolean {
  return (
    location.latitude >= PHNOM_PENH_DEMO_BOUNDS.south &&
    location.latitude <= PHNOM_PENH_DEMO_BOUNDS.north &&
    location.longitude >= PHNOM_PENH_DEMO_BOUNDS.west &&
    location.longitude <= PHNOM_PENH_DEMO_BOUNDS.east
  );
}

